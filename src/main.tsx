import React from 'react';
import ReactDOM from 'react-dom/client';
import App from './App';
import './styles.css';
const root = document.getElementById('root')!;
const privacyPath = `${import.meta.env.BASE_URL}privacidade`;
const page = [privacyPath, `${privacyPath}/`, `${privacyPath}/index.html`].includes(window.location.pathname) ? 'privacy' : 'home';
if (page === 'privacy') document.title = 'Política de privacidade | GTAM Ferramentaria';
const app = <React.StrictMode><App page={page} /></React.StrictMode>;
if (root.hasChildNodes()) ReactDOM.hydrateRoot(root, app);
else ReactDOM.createRoot(root).render(app);
